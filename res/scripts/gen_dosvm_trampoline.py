"""Generate dosvm_trampoline.h from programs/dos/trampoline.nasm.

Why a generated byte array instead of a .asm object
---------------------------------------------------
kernel/Makefile forces ``-f elf64`` on every ``modules/**/*.asm``
and links the object into the higher-half kernel image.  A 16-bit real-mode
trampoline must instead execute at the IDENTITY-MAPPED physical address
0x70000 (the higher half is unmapped the instant CR0.PG is cleared).  So we
build it as a flat binary with NASM (``-f bin``, ``org 0x70000``) and embed
the bytes in a C++ array; the Tier1 component memcpy()s them to 0x70000 at
boot.  No linker script changes, no KASLR relocation fixups.

The generated header is checked in, so a normal build needs neither NASM nor
Python.  Re-run this script only when the .nasm source changes::

    python3 res/scripts/gen_dosvm_trampoline.py
    # or, on Windows with WSL:
    wsl -e bash -lc 'cd /mnt/c/ZSY/SkylineSystem && python3 res/scripts/gen_dosvm_trampoline.py'

Self-checks performed here
--------------------------
* flat binary is non-empty and < 4 KiB (fits below the GDT/IVT area)
* every byte is emitted, with an assertion-friendly size macro
* the embedded GDT descriptor base at gdt_desc matches the blob layout
"""

import os
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ROOT, "programs", "dos", "trampoline.nasm")
DST = os.path.join(ROOT, "kernel", "include", "arch", "x86_64",
                   "dosvm", "dosvm_trampoline.h")

LOW_BASE = 0x70000
MAX_SIZE = 0x1000


def build_blob() -> bytes:
    # Prefer `nasm` on PATH; on Windows the WSL build host provides it.
    with open(SRC, "rb") as _:
        pass  # fail early with a clear message below if NASM is missing
    out = os.path.join(ROOT, "programs", "dos", ".trampoline.bin.tmp")
    try:
        subprocess.run(["nasm", "-f", "bin", "-Wall", "-Werror", SRC, "-o", out],
                       check=True, capture_output=True)
        with open(out, "rb") as fh:
            data = fh.read()
    except FileNotFoundError:
        raise SystemExit("NASM not found on PATH; run this script inside WSL")
    except subprocess.CalledProcessError as exc:
        raise SystemExit("NASM failed:\n" + exc.stderr.decode("utf-8", "replace"))
    finally:
        if os.path.exists(out):
            os.remove(out)
    return data


def emit(data: bytes) -> str:
    lines = [
        "// SPDX-FileCopyrightText: 2026 Yo-yo-ooo",
        "// SPDX-License-Identifier: GPL-2.0-only",
        "// GENERATED FILE -- DO NOT EDIT.",
        "// Source: programs/dos/trampoline.nasm",
        "// Regenerate: python3 res/scripts/gen_dosvm_trampoline.py",
        "// NASM -f bin, org 0x70000; copied verbatim to physical 0x70000.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "#define DOSVM_TRAMP_BLOB_SIZE %du" % len(data),
        "",
        "static const uint8_t kDosvmTrampoline[DOSVM_TRAMP_BLOB_SIZE] = {",
    ]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + " ".join("0x%02x," % b for b in chunk)
                     + "  // +0x%03x" % i)
    lines += ["};", "", ""]
    return "\n".join(lines)


def main() -> int:
    data = build_blob()
    if not data:
        raise SystemExit("empty trampoline blob")
    if len(data) > MAX_SIZE:
        raise SystemExit("trampoline blob %d B exceeds %d B budget; "
                         "it would overwrite the GDT at +0x2000" % (len(data), MAX_SIZE))
    # The blob ends with gdt_desc: dw limit; dq base.  Verify the base points
    # at the in-blob GDT (defensive: catches an accidental org/section change).
    tail = data[-10:]
    limit, base = struct.unpack_from("<HQ", tail)
    if limit != 47 or not (LOW_BASE <= base < LOW_BASE + len(data)):
        raise SystemExit("gdt_desc sanity check failed: limit=%d base=0x%x"
                         % (limit, base))
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(emit(data))
    print("[dosvm] wrote %s (%d bytes, gdt_desc=0x%x)"
          % (os.path.relpath(DST, ROOT), len(data), base))
    return 0


if __name__ == "__main__":
    sys.exit(main())
